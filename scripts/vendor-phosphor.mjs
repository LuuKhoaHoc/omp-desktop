#!/usr/bin/env node
// Regenerates src/design/ui/icon-paths.js from the official Phosphor icon
// package, once, at vendoring time (nothing installs it for a build):
//
//   node scripts/vendor-phosphor.mjs 2.1.1
//                                    ^@phosphor-icons/core
//
// The app's icon names (ui/icons.jsx `<Icon name>`) map onto Phosphor's in
// NAMES below; each entry copies the inner markup of that icon's bold
// weight (viewBox 0 0 256 256, filled) verbatim. `flip` mirrors an icon
// horizontally (the rail toggle is the sidebar toggle's mirror image).
// A `/*!` banner records the package, its version and its MIT license.
// Never hand-edit the output; edit NAMES and re-run this script.
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = {
  plus: "plus", minus: "minus", close: "x", check: "check",
  play: "play", pause: "pause", stop: "stop", refresh: "arrows-clockwise",
  copy: "copy", trash: "trash", file: "file-text", folder: "folder-simple",
  edit: "pencil-simple", diff: "plus-minus", bash: "terminal", search: "magnifying-glass",
  grep: "list-magnifying-glass", test: "flask", build: "hammer", web: "globe-simple",
  plan: "list-checks", thinking: "brain", agent: "robot", sparkle: "sparkle",
  bolt: "lightning", radar: "crosshair-simple", voice: "microphone", conversation: "chats-circle",
  context: "chart-pie-slice", tokens: "coins", cost: "chart-bar",
  arrow: "arrow-right", arrowUp: "arrow-up", chev: "caret-down", chevR: "caret-right",
  home: "house-simple", back: "arrow-left", external: "arrow-square-out",
  sidebar: "sidebar-simple", rail: { name: "sidebar-simple", flip: true },
  split: "columns", grid: "squares-four", minimap: "map-trifold", layers: "stack-simple",
  focus: "arrows-out", circle: "circle", dot: "dot-outline", warn: "warning", info: "info",
  clock: "clock-counter-clockwise", live: "broadcast", goal: "target",
  branch: "git-branch", merge: "git-merge", commit: "git-commit", tag: "tag", diff2: "git-diff",
  command: "command", image: "image", link: "link", send: "paper-plane-tilt",
  cog: "gear-six", terminal: "terminal-window",
};

const version = process.argv[2];
if (!/^\d+\.\d+\.\d+$/.test(version ?? "")) {
  console.error("usage: node scripts/vendor-phosphor.mjs <@phosphor-icons/core version>, e.g. 2.1.1");
  process.exit(2);
}
const out = resolve(dirname(fileURLToPath(import.meta.url)), "..", "src", "design", "ui", "icon-paths.js");
const work = mkdtempSync(join(tmpdir(), "vendor-phosphor-"));

try {
  const pack = spawnSync("npm", ["pack", `@phosphor-icons/core@${version}`, "--pack-destination", work],
    { stdio: "inherit", shell: process.platform === "win32" });
  if (pack.status !== 0) throw new Error("npm pack failed");
  const tgz = readdirSync(work).find(f => f.endsWith(".tgz"));
  if (spawnSync("tar", ["-xzf", join(work, tgz), "-C", work], { stdio: "inherit" }).status !== 0) throw new Error("tar failed");
  const bold = join(work, "package", "assets", "bold");

  const paths = {};
  for (const [ours, spec] of Object.entries(NAMES)) {
    const { name, flip } = typeof spec === "string" ? { name: spec, flip: false } : spec;
    const svg = readFileSync(join(bold, `${name}-bold.svg`), "utf8");
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
    if (!inner || /<script|\son\w+=/i.test(inner)) throw new Error(`unexpected markup in ${name}`);
    paths[ours] = flip ? `<g transform="matrix(-1 0 0 1 256 0)">${inner}</g>` : inner;
  }
  const license = readFileSync(join(work, "package", "LICENSE"), "utf8").split(/\r?\n/).find(l => /Copyright/.test(l));
  const body = Object.entries(paths).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  writeFileSync(out, `/*! @phosphor-icons/core ${version} (bold weight), MIT License, ${license.trim()}.
    Generated by scripts/vendor-phosphor.mjs; never hand-edit. */
window.OMP_ICON_PATHS = Object.freeze({
${body}
});
`);
  console.log(`wrote ${Object.keys(paths).length} icons to ${out}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
